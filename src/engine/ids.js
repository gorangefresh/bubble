let counter = 0;

/**
 * Монотонный идентификатор сущности.
 *
 * Было: `${type}-${parent}-${Date.now()}`. Всё, что создавалось в пределах
 * одной миллисекунды, получало одинаковый id — а Destroyer на один клик
 * стреляет сразу из четырёх ракетниц в одном тике, и все четыре ракеты
 * записывались в реестр снарядов под одним ключом. Оставалась одна.
 */
export default function nextId(prefix) {
    counter += 1;
    return `${prefix}-${counter}`;
}
