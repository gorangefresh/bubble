/**
 * Константы мира и шага симуляции.
 */

/**
 * Раньше каждая сущность крутила свою цепочку setTimeout со своим шагом:
 * враги и пули — 30 мс, танк — 50 мс. Скорость задавалась в «пикселях за тик»,
 * то есть зависела от того, как браузер выдерживает таймеры. Теперь шаг
 * симуляции единый, и все скорости приведены к пикселям в секунду через
 * этот хелпер — числа остались те же, геймплейный «фил» не изменился.
 */
export const perTick = (px, tickMs) => (px * 1000) / tickMs;

/** Старые шаги таймеров — нужны только для пересчёта скоростей. */
export const LEGACY_TICK = {
    entity: 30, // враги, пули
    tank: 50    // игрок
};

/** Фиксированный шаг симуляции, мс. */
export const STEP_MS = 1000 / 60;

/**
 * Максимальная дельта за кадр. Без клампа после сворачивания вкладки
 * аккумулятор накапливает минуты, и цикл пытается догнать их за один кадр,
 * вешая страницу.
 */
export const MAX_FRAME_MS = 250;

/** Диаметр и радиус игрового поля («пузыря» уровня). */
export const FIELD_D = 800;
export const FIELD_R = FIELD_D / 2;

/**
 * Размер ячейки сетки коллизий. Самый крупный участник — тяжёлый враг
 * (диаметр 60), поэтому 64 даёт не больше четырёх ячеек на объект.
 */
export const CELL_SIZE = 64;

/**
 * Длительность перелёта между уровнями. Должна совпадать с CSS-переходом
 * корпуса: раньше таймер стоял на 600 мс при переходе .7s, и танк дёргался
 * в конце анимации.
 */
export const TRAVEL_MS = 700;
